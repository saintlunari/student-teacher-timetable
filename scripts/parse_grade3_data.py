def parse_csv_block(raw_text, subject):
    reader = csv.reader(io.StringIO(raw_text.strip()))
    items = []
    for row in reader:
        if not row or len(row) < 6: continue
        unit = row[1].strip()
        topic = row[2].strip()
        lesson = row[3].strip()
        totalLesson = int(row[4].strip())
        pages = row[5].strip()
        achieve = row[-1].strip() if len(row) >= 7 and row[-1].strip().startswith('[') else ''
        items.append({
            'grade': 3,
            'semester': '2학기',
            'subject': subject,
            'unit': unit,
            'topic': topic,
            'lesson': lesson,
            'totalLesson': totalLesson,
            'pages': pages,
            'achievement': achieve
        })
    return items

